      'cat_kitchen': 'Cocina',
      'cat_kitchen_desc': 'Conversiones de cocina y recetas',
      'cat_moreTools': 'Más herramientas',
      'cat_moreTools_desc': 'Slate, aleatorizador y extras cotidianos',
    },
  };

  String tr(String key) {
    final langCode = locale.languageCode;
    return _localizedValues[langCode]?[key] ??
        _localizedValues['en']?[key] ??
        key;
  }

  String translate(String key) => tr(key);

  String categoryLabel(ToolCategory c) =>
      c == ToolCategory.all ? tr('all_tools') : tr('cat_${c.name}');

  String categoryDescription(ToolCategory c) =>
      c == ToolCategory.all ? c.description : tr('cat_${c.name}_desc');
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => ['en', 'ta', 'hi', 'es'].contains(locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) async {
    return AppLocalizations(locale);
  }

  @override
  bool shouldReload(AppLocalizationsDelegate old) => false;
}

/// Localised category name for the current app language. The enum's own
/// `label`/`description` stay as the English source of truth.
String categoryLabel(BuildContext context, ToolCategory category) =>
    AppLocalizations.of(context).categoryLabel(category);

String categoryDescription(BuildContext context, ToolCategory category) =>
    AppLocalizations.of(context).categoryDescription(category);
